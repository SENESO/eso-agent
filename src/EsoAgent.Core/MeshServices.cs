/// <summary>Deterministic virtual-IP allocation from the fleet mesh range (10.77.0.0/16).</summary>
public static class IpAllocator
{
    public const string DefaultCidr = "10.77.0.0/16";
    /// <summary>10.77.0.1 is reserved for the fleet server itself if it joins the mesh.</summary>
    public const string ServerIp = "10.77.0.1";

    /// <summary>Returns the lowest free host address ≥ .2, skipping every address in <paramref name="used"/>.</summary>
    public static string Allocate(IReadOnlyCollection<string> used, string cidr = DefaultCidr)
    {
        var parts = cidr.Split('/');
        var network = IPAddress.Parse(parts[0]).GetAddressBytes();
        var prefix = int.Parse(parts[1]);
        var usedSet = new HashSet<string>(used) { ServerIp };
        var hostBits = 32 - prefix;
        var total = 1L << hostBits;

        var baseValue = ((long)network[0] << 24) | ((long)network[1] << 16) | ((long)network[2] << 8) | network[3];
        for (long offset = 2; offset < total - 1; offset++) // skip network (.0), server (.1), broadcast
        {
            var v = baseValue + offset;
            var candidate = $"{(v >> 24) & 255}.{(v >> 16) & 255}.{(v >> 8) & 255}.{v & 255}";
            if (!usedSet.Contains(candidate)) return candidate;
        }
        throw new InvalidOperationException($"Mesh range {cidr} exhausted.");
    }
}

/// <summary>Builds wg-quick style WireGuard configs from mesh state (pure; unit-tested).</summary>
public static class WgConfigBuilder
{
    public static string Build(string privateKeyB64, string virtualIp, int listenPort, IReadOnlyList<MeshPeerInfo> peers, int relayShimBasePort = 51821, string? exitNodeCode = null)
        => RenderText(BuildModel(privateKeyB64, virtualIp, listenPort, peers, relayShimBasePort, exitNodeCode));

    /// <summary>
    /// The structured form of the same configuration <see cref="Build"/> renders
    /// as wg-quick text. The embedded mesh engine (MeshEngineSupervisor) consumes
    /// this model and translates it to WireGuard UAPI operations, so the text
    /// config and the engine config can never drift apart: both come from here.
    /// </summary>
    public static WgInterfaceConfig BuildModel(string privateKeyB64, string virtualIp, int listenPort, IReadOnlyList<MeshPeerInfo> peers, int relayShimBasePort = 51821, string? exitNodeCode = null)
    {
        var model = new WgInterfaceConfig
        {
            PrivateKeyB64 = privateKeyB64,
            VirtualIp = virtualIp,
            ListenPort = listenPort,
        };
        var relayIndex = 0;
        foreach (var peer in peers)
        {
            // Exit node (v1.2): the designated peer carries the default route —
            // WireGuard cryptokey routing sends 0.0.0.0/0 to it, and it NATs
            // the traffic out (see MeshApplier's exit-node step).
            var isExit = exitNodeCode != null && peer.Code.Equals(exitNodeCode, StringComparison.OrdinalIgnoreCase);
            var allowed = isExit
                ? new List<string> { "0.0.0.0/0" }
                : new List<string> { $"{peer.VirtualIp}/32" };
            foreach (var subnet in peer.ApprovedSubnets)
                if (!allowed.Contains(subnet)) allowed.Add(subnet);
            string? endpoint = null;
            if (peer.Relay)
                endpoint = $"127.0.0.1:{relayShimBasePort + relayIndex++}"; // local shim → server relay
            else if (!string.IsNullOrWhiteSpace(peer.Endpoint))
                endpoint = peer.Endpoint;
            model.Peers.Add(new WgPeerConfig
            {
                Name = peer.Name,
                Code = peer.Code,
                PublicKeyB64 = peer.WgPublicKey,
                AllowedIps = allowed,
                Endpoint = endpoint,
                PersistentKeepalive = 25,
            });
        }
        return model;
    }

    /// <summary>Renders a structured config as wg-quick text (the exact format
    /// <see cref="Build"/> has always produced).</summary>
    public static string RenderText(WgInterfaceConfig model)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by EsoAgent from fleet mesh state — do not edit by hand.");
        sb.AppendLine("[Interface]");
        sb.AppendLine($"PrivateKey = {model.PrivateKeyB64}");
        sb.AppendLine($"Address = {model.VirtualIp}/32");
        sb.AppendLine($"ListenPort = {model.ListenPort}");
        foreach (var peer in model.Peers)
        {
            sb.AppendLine();
            sb.AppendLine($"# {peer.Name} ({peer.Code})");
            sb.AppendLine("[Peer]");
            sb.AppendLine($"PublicKey = {peer.PublicKeyB64}");
            sb.AppendLine($"AllowedIPs = {string.Join(", ", peer.AllowedIps)}");
            if (!string.IsNullOrWhiteSpace(peer.Endpoint))
                sb.AppendLine($"Endpoint = {peer.Endpoint}");
            sb.AppendLine($"PersistentKeepalive = {peer.PersistentKeepalive}");
        }
        return sb.ToString();
    }
}

/// <summary>
/// Compiles owner/operator ACL rules into per-device inbound firewall plans.
/// Default posture: every approved fleet member may reach every other member's
/// agent port; everything else inbound from the mesh is denied. ACL rules add
/// allows on top. WireGuard AllowedIPs stay full-mesh (cryptokey routing is not
/// a port firewall) — the port-level policy lives in this firewall plan, which
/// the agent applies with the platform firewall.
///
/// The default posture also carries what the mesh data plane itself needs
/// (§27, field-proven 2026-11-23): the P2P port (8742 — discovery and
/// sessions over the mesh bootstrap route), ICMP echo (diagnostics — a
/// ping that can never arrive cannot distinguish "tunnel down" from
/// "firewall closed"), and return traffic for connections the device
/// itself initiated (a bare RST/SYN-ACK reply to an outbound SYN was
/// dropped by the plan's own DROP — the plan only ever allowed the
/// agent port as a destination, and a reply's destination is the
/// outbound socket's ephemeral port). The allow-list stays explicit:
/// named ports only, mesh sources only.
/// </summary>
public static class AclCompiler
{
    public sealed record DeviceView(string Code, string VirtualIp, IReadOnlyList<string> Groups);

    /// <summary>Windows dynamic (ephemeral) port range — the destination
    /// ports of reply traffic for outbound connections. Linux renderers
    /// use conntrack state instead and ignore the range.</summary>
    public const string ReturnTrafficPortRange = "49152-65535";

    /// <summary>ICMP type carried in <see cref="MeshFirewallRule.Port"/>
    /// for icmp rules: 8 = echo request. Renderers must emit it as the
    /// ICMP type, never as a port (old renderers fail such a rule
    /// closed: netsh rejects "ICMP", iptables rejects --dport with -p
    /// icmp — no over-broad rule can result).</summary>
    public const int IcmpEchoRequestType = 8;

    public static Dictionary<string, MeshFirewallPlan> Compile(IReadOnlyList<DeviceView> devices, IReadOnlyList<AclRule> rules, int agentPort, int p2pPort = P2pDefaults.ListenPort)
    {
        var plans = devices.ToDictionary(d => d.Code, d => new MeshFirewallPlan { DeviceCode = d.Code });

        void AddAllow(string targetCode, string fromCidr, int port, string note, string protocol = "tcp", bool returnTraffic = false, string? portRange = null)
        {
            if (!plans.TryGetValue(targetCode, out var plan)) return;
            if (plan.AllowInbound.Any(r => r.FromCidr == fromCidr && r.Port == port && r.Protocol == protocol && r.ReturnTraffic == returnTraffic)) return;
            plan.AllowInbound.Add(new MeshFirewallRule { FromCidr = fromCidr, Port = port, Protocol = protocol, Note = note, ReturnTraffic = returnTraffic, PortRange = portRange });
        }

        // Default posture: agent port + P2P port + ICMP echo + return
        // traffic, reachable from all fleet members.
        foreach (var target in devices)
        foreach (var source in devices)
        {
            if (source.Code == target.Code) continue;
            AddAllow(target.Code, $"{source.VirtualIp}/32", agentPort, "default: fleet agent port");
            AddAllow(target.Code, $"{source.VirtualIp}/32", p2pPort, "default: fleet p2p port");
            AddAllow(target.Code, $"{source.VirtualIp}/32", IcmpEchoRequestType, "default: mesh diagnostics (icmp echo)", protocol: "icmp");
            AddAllow(target.Code, $"{source.VirtualIp}/32", 49152, "default: return traffic for outbound mesh connections",
                returnTraffic: true, portRange: ReturnTrafficPortRange);
        }

        IEnumerable<DeviceView> Expand(string selector)
        {
            if (selector.StartsWith("group:", StringComparison.OrdinalIgnoreCase))
            {
                var group = selector["group:".Length..];
                return devices.Where(d => d.Groups.Contains(group, StringComparer.OrdinalIgnoreCase));
            }
            return devices.Where(d => d.Code.Equals(selector, StringComparison.OrdinalIgnoreCase));
        }

        foreach (var rule in rules)
        {
            var sources = Expand(rule.From).ToList();
            var targets = Expand(rule.To).ToList();
            var ports = rule.Ports.Count == 0 ? new List<int> { 0 } : rule.Ports; // 0 = any
            foreach (var target in targets)
            foreach (var source in sources)
            {
                if (source.Code == target.Code) continue;
                foreach (var port in ports)
                    AddAllow(target.Code, $"{source.VirtualIp}/32", port, $"acl: {rule.From} -> {rule.To}");
            }
        }
        return plans;
    }
}

/// <summary>
/// MagicDNS-lite: merges the fleet name→virtual-IP map into the OS hosts file
/// inside a marked block (idempotent; unit-tested as a pure string transform).
/// </summary>
public static class HostsFileSync
{
    public const string BeginMarker = "# esoagent-mesh begin";
    public const string EndMarker = "# esoagent-mesh end";

    public static string Merge(string existingContent, IReadOnlyDictionary<string, string> nameToIp)
    {
        var lines = existingContent.Replace("\r\n", "\n").Split('\n').ToList();
        var output = new List<string>();
        var inBlock = false;
        foreach (var line in lines)
        {
            if (line.Trim() == BeginMarker) { inBlock = true; continue; }
            if (line.Trim() == EndMarker) { inBlock = false; continue; }
            if (!inBlock) output.Add(line);
        }
        while (output.Count > 0 && output[^1].Length == 0) output.RemoveAt(output.Count - 1);
        if (nameToIp.Count > 0)
        {
            output.Add(BeginMarker);
            foreach (var (name, ip) in nameToIp.OrderBy(kv => kv.Key, StringComparer.OrdinalIgnoreCase))
                output.Add($"{ip} {name}");
            output.Add(EndMarker);
        }
        return string.Join("\n", output) + "\n";
    }
}

/// <summary>
/// DERP-style relay framing. A shim on each device wraps WireGuard packets for
/// relayed peers as: [32B source WG pubkey][32B destination WG pubkey][payload].
/// The server relay learns pubkey→UDP-endpoint from every framed packet it sees
/// (and from zero-payload registration packets) and forwards payloads keyed by
/// the destination pubkey. The relay only ever handles WireGuard ciphertext.
/// </summary>
public static class RelayFraming
{
    public const int HeaderSize = 64;

    public static byte[] Wrap(byte[] sourcePubKey, byte[] destPubKey, ReadOnlySpan<byte> payload)
    {
        if (sourcePubKey.Length != 32 || destPubKey.Length != 32)
            throw new ArgumentException("WireGuard public keys are 32 bytes.");
        var frame = new byte[HeaderSize + payload.Length];
        sourcePubKey.CopyTo(frame, 0);
        destPubKey.CopyTo(frame, 32);
        payload.CopyTo(frame.AsSpan(HeaderSize));
        return frame;
    }

    public static bool TryParse(byte[] frame, out string sourceKeyB64, out string destKeyB64, out byte[] payload)
    {
        sourceKeyB64 = destKeyB64 = ""; payload = Array.Empty<byte>();
        if (frame.Length < HeaderSize) return false;
        sourceKeyB64 = Convert.ToBase64String(frame, 0, 32);
        destKeyB64 = Convert.ToBase64String(frame, 32, 32);
        payload = frame[HeaderSize..];
        return true;
    }
}

/// <summary>
/// <summary>
/// Turns a compiled firewall plan into platform commands (pure; the applier runs
/// them through the audited process runner). Windows: netsh rules all named
/// "EsoAgentMesh" so one delete clears the set. Linux: a dedicated iptables
/// chain jumped to from INPUT for mesh-range sources only.
///
/// Rule shapes (§27): icmp rules carry the ICMP type in Port (8 = echo
/// request) and render as an echo-only allow, never as a port; return-traffic
/// rules render as a conntrack ESTABLISHED,RELATED accept on Linux and as an
/// allow for the dynamic port range on Windows; a PortRange renders as a port
/// range on both. Renderers never emit Port as a port for an icmp rule —
/// an old renderer would have failed such a rule closed, and this one must
/// not silently widen it.
/// </summary>
public static class MeshFirewallCommands
{
    public static List<string[]> Windows(MeshFirewallPlan plan)
    {
        var commands = new List<string[]>
        {
            new[] { "netsh", "advfirewall", "firewall", "delete", "rule", "name=EsoAgentMesh" },
        };
        foreach (var rule in plan.AllowInbound)
        {
            var args = new List<string>
            {
                "netsh", "advfirewall", "firewall", "add", "rule", "name=EsoAgentMesh",
                "dir=in", "action=allow",
                $"remoteip={rule.FromCidr}",
            };
            if (rule.Protocol.Equals("icmp", StringComparison.OrdinalIgnoreCase))
            {
                // Echo request only (type 8); never a port.
                args.Add($"protocol=icmpv4:{rule.Port},any");
            }
            else
            {
                args.Add($"protocol={rule.Protocol.ToUpperInvariant()}");
                var localPort = rule.PortRange ?? (rule.Port > 0 ? rule.Port.ToString() : null);
                if (localPort != null) args.Add($"localport={localPort}");
            }
            commands.Add(args.ToArray());
        }
        return commands;
    }

    public static List<string[]> Linux(MeshFirewallPlan plan, string meshCidr = IpAllocator.DefaultCidr)
    {
        var commands = new List<string[]>
        {
            new[] { "iptables", "-N", "ESOAGENT_MESH" },
            new[] { "iptables", "-F", "ESOAGENT_MESH" },
        };
        if (plan.AllowInbound.Any(r => r.ReturnTraffic))
        {
            // Replies to connections this device initiated (RST/SYN-ACK to an
            // outbound SYN): the plan's own DROP would eat them without this.
            // The box's outer firewall carries the same rule, but the plan
            // must be self-contained — a plain Linux host has only this chain.
            commands.Add(new[] { "iptables", "-A", "ESOAGENT_MESH", "-m", "conntrack", "--ctstate", "ESTABLISHED,RELATED", "-j", "ACCEPT" });
        }
        foreach (var rule in plan.AllowInbound)
        {
            if (rule.ReturnTraffic) continue; // covered by the conntrack rule above; PortRange is Windows-only
            var args = new List<string> { "iptables", "-A", "ESOAGENT_MESH", "-s", rule.FromCidr, "-p", rule.Protocol };
            if (rule.Protocol.Equals("icmp", StringComparison.OrdinalIgnoreCase))
            {
                args.Add("--icmp-type"); args.Add(rule.Port.ToString()); // Port carries the ICMP type (8 = echo request)
            }
            else if (rule.PortRange != null)
            {
                args.Add("--dport"); args.Add(rule.PortRange.Replace('-', ':'));
            }
            else if (rule.Port > 0) { args.Add("--dport"); args.Add(rule.Port.ToString()); }
            args.Add("-j"); args.Add("ACCEPT");
            commands.Add(args.ToArray());
        }
        commands.Add(new[] { "iptables", "-A", "ESOAGENT_MESH", "-j", "DROP" });
        commands.Add(new[] { "iptables", "-C", "INPUT", "-s", meshCidr, "-j", "ESOAGENT_MESH" });
        commands.Add(new[] { "iptables", "-A", "INPUT", "-s", meshCidr, "-j", "ESOAGENT_MESH" }); // runs only if -C failed; applier tolerates its failure otherwise
        return commands;
    }
}

/// <summary>Enrollment-key helpers: keys are random 128-bit, shown once, stored as SHA-256 hashes.</summary>
public static class EnrollmentKeys
{
    public static string Generate()
        => "eso-enroll-" + Convert.ToHexString(RandomNumberGenerator.GetBytes(16)).ToLowerInvariant();

    public static string Hash(string key)
        => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(key.Trim()))).ToLowerInvariant();
}
